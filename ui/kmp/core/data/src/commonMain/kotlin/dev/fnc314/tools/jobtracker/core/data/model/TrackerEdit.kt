package dev.fnc314.tools.jobtracker.core.data.model

import kotlin.time.Instant

/**
 * Proposed modification or status update staged for candidate approval before mutation.
 *
 * Emitted by automated ingestion pipelines (such as Gmail synchronization or Google Sheets imports)
 * to ensure that all changes to the Firestore system of record remain strictly opt-in.
 *
 * @property id Unique edit proposal identifier.
 * @property applicationId Target application slug to be modified.
 * @property kind Originating workflow kind [TrackerEditKind] (e.g. Email Sync, Sheet Sync).
 * @property state Current lifecycle review state [TrackerEditState] (Pending, Approved, Rejected, Expired).
 * @property trigger Automation trigger [Trigger] responsible for initiating the edit proposal.
 * @property changes List of concrete field-level proposed alterations [EditChange].
 * @property unmatched Unmatched raw metadata fields extracted from external data sources.
 * @property sourceEmail Source email metadata [SourceEmail] if generated from an incoming message.
 * @property scope Target document collection scope [EditScope].
 * @property confidence Machine extraction confidence rating [Confidence].
 * @property createdAt Timestamp when the edit proposal was staged.
 * @property expiresAt Timestamp after which an unreviewed pending proposal automatically expires.
 * @see TrackerEditKind
 * @see TrackerEditState
 * @see EditChange
 */
public data class TrackerEdit(
    public val id: String,
    public val applicationId: String,
    public val kind: TrackerEditKind,
    public val state: TrackerEditState,
    public val trigger: Trigger,
    public val changes: List<EditChange>,
    public val unmatched: List<EditUnmatched>,
    public val sourceEmail: SourceEmail?,
    public val scope: EditScope?,
    public val confidence: Confidence,
    public val createdAt: Instant?,
    public val expiresAt: Instant?,
)

/**
 * A discrete field-level modification proposed within a [TrackerEdit].
 *
 * @property field Name of the target document property to update.
 * @property oldValue Previous value before the proposed mutation.
 * @property newValue Proposed new value to write.
 * @property reason Justification or natural-language explanation generated by the parser or agent.
 */
public data class EditChange(
    public val field: String,
    public val oldValue: String,
    public val newValue: String,
    public val reason: String,
)

/**
 * Unmatched or unparsed property extracted during data ingestion.
 *
 * @property field Name of the unmapped source field.
 * @property value Raw extracted string value.
 */
public data class EditUnmatched(
    public val field: String,
    public val value: String,
)

/**
 * Provenance metadata detailing the email message that prompted a [TrackerEdit].
 *
 * @property messageId Unique Gmail or RFC 2822 message identifier.
 * @property from Sender address header.
 * @property subject Email subject line.
 */
public data class SourceEmail(
    public val messageId: String,
    public val from: String,
    public val subject: String,
)

/**
 * Document target coordinates for applying an approved [TrackerEdit].
 *
 * @property collection Firestore collection name (e.g., `"applications"`).
 * @property documentId Firestore document key.
 */
public data class EditScope(
    public val collection: String,
    public val documentId: String,
)
